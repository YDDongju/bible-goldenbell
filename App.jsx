function Confetti({ n = 16 }) {
  const cols = [C.grass, C.gold, C.lapis, C.heart, C.diamond, C.emerald];
  const bits = Array.from({ length: n }, (_, i) => ({
    left: Math.round((i / n) * 100 + (Math.random() * 8 - 4)),
    d: (1.1 + Math.random() * 1.1).toFixed(2),
    delay: (Math.random() * 0.5).toFixed(2),
    c: cols[i % cols.length], s: 6 + Math.round(Math.random() * 6),
  }));
  return (
    <div aria-hidden style={{ position: "absolute", inset: 0, overflow: "hidden", pointerEvents: "none" }}>
      {bits.map((b, i) => (
        <span key={i} className="conf" style={{ position: "absolute", top: -14, left: `${b.left}%`, width: b.s, height: b.s,
          background: b.c, boxShadow: `0 0 0 2px ${C.outline}`, animationDuration: `${b.d}s`, animationDelay: `${b.delay}s` }} />
      ))}
    </div>
  );
}

